#!/usr/bin/env python3
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests"))
import rise_net as r

MAXB = 8 * 76

def collect(paths):
    msgs = set()
    for path in paths:
        try:
            for pk, m in r.switch_messages(path):
                if m["ptype"] == 0x68 and 5 <= len(bytes(m["payload"])) <= 80:
                    msgs.add(bytes(m["payload"]))
        except Exception as e:
            print("skipped %s: %s" % (path, e))
    return sorted(msgs)

def solve(msgs):
    lens = sorted({len(p) for p in msgs})
    lcol = {L: MAXB + i for i, L in enumerate(lens)}
    piv, bad = {}, 0
    for p in msgs:
        key = p[3]
        mask, n = 1 << lcol[len(p)], 0
        for byte in reversed(bytes(b ^ key for b in p[4:])):
            for i in range(8):
                if byte >> i & 1:
                    mask |= 1 << n
                n += 1
        h = int.from_bytes(p[:4], "big")
        while mask:
            t = mask.bit_length() - 1
            if t in piv:
                pm, ph = piv[t]
                mask ^= pm
                h ^= ph
            else:
                piv[t] = (mask, h)
                break
        else:
            bad += h != 0
    keys = sorted(piv)
    for t in keys:
        m, h = piv[t]
        for u in keys:
            if u > t and piv[u][0] >> t & 1:
                pm, ph = piv[u]
                piv[u] = (pm ^ m, ph ^ h)
    det = {t: piv[t][1] for t in keys if piv[t][0] == 1 << t}
    return lens, lcol, det, bad

def main():
    args = sys.argv[1:]
    out = "bridge/headertable.py"
    if "--out" in args:
        i = args.index("--out"); out = args[i + 1]; del args[i:i + 2]
    if not args:
        print("Usage: python3 tools/solve_header.py capture.txt [--out bridge/headertable.py]"); return
    msgs = collect(args)
    lens, lcol, det, bad = solve(msgs)
    nbits = 0
    while nbits in det:
        nbits += 1
    nbits -= nbits % 8
    C = {L: det[lcol[L]] for L in lens if lcol[L] in det and L <= 4 + nbits // 8}
    print("%d messages, %d inconsistent; %d data bits determined (%d bytes), %d lengths with a constant" %
          (len(msgs), bad, nbits, nbits // 8, len(C)))
    D = [det[n] for n in range(nbits)]
    with open(out, "w") as f:
        f.write('"""Generated by tools/solve_header.py from captures: the game-message checksum table (see gamemsg.py)."""\n')
        f.write("D = [\n" + "\n".join("    " + ", ".join("0x%08x" % d for d in D[i:i + 6]) + "," for i in range(0, len(D), 6)) + "\n]\n")
        f.write("C = {\n" + "\n".join("    %d: 0x%08x," % (L, C[L]) for L in sorted(C)) + "\n}\n")
    print("wrote", out)

if __name__ == "__main__":
    main()
